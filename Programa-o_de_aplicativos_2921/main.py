#Exemplo com Média

nome = input("Digite o nome do aluno: ")

nota1 = float(input("Digite a primeira nota: "))
nota2 = float(input("Digite a segunda nota: "))

media = (nota1 + nota2) / 2

print("RESULTADO")

print(f"Aluno: {nome}")
print(f"nota1: {nota1}")
print(f"nota2: {nota2}")
print(f"media: {media}")